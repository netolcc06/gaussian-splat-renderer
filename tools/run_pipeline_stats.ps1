<#
.SYNOPSIS
  Phase 6: compiled-pipeline statistics (VK_KHR_pipeline_executable_properties) of every
  renderer and render-loop variant, as JSON + one markdown table.

.DESCRIPTION
  Runs `gsplat --pipeline-stats <json>` (creates the renderer with statistics capture, queries
  every pipeline, exits) for each configuration below, then tabulates per pipeline:
  registers per thread, shared memory per workgroup, local memory per thread (spills),
  binary size, and the occupancy the register count allows on this GPU.

  NVIDIA (driver 595.71) reports "Local Memory Size" with bit 36 set (2^36 + bytes): the table
  subtracts it (verified: a pipeline with data-dependent array indexing reports 2^36 + 384).
  Occupancy model (Ada, RTX 4060 Laptop): 65536 registers, 1536 threads, 100 KB shared memory
  and 24 workgroups per SM; registers are allocated per warp in units of 256.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File tools/run_pipeline_stats.ps1
#>
param(
    [string]$Config = 'Release',
    [string]$Scene = 'data/scenes/bonsai_30k/point_cloud.ply',
    [string]$OutDir = 'docs/notes/bench',
    [string]$Markdown = 'docs/notes/bench/phase6_pipeline_stats.md'
)
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root
$exe = Join-Path $root "build/bin/$Config/gsplat.exe"
$inv = [System.Globalization.CultureInfo]::InvariantCulture

$configs = @(
    @{ Name = 'splat'; Args = @('--renderer', 'splat') },
    @{ Name = 'splat-gpusort'; Args = @('--renderer', 'splat-gpusort') },
    @{ Name = 'splat-tiles (default)'; Args = @('--renderer', 'splat-tiles') },
    @{ Name = 'splat-tiles p32'; Args = @('--renderer', 'splat-tiles', '--render-splat', 'p32') },
    @{ Name = 'splat-tiles tile 8'; Args = @('--renderer', 'splat-tiles', '--tile-size', '8') },
    @{ Name = 'splat-tiles batch 512'; Args = @('--renderer', 'splat-tiles', '--render-batch', '512') },
    @{ Name = 'splat-tiles shared aos'; Args = @('--renderer', 'splat-tiles', '--render-shared', 'aos') },
    @{ Name = 'splat-tiles fp16'; Args = @('--renderer', 'splat-tiles', '--render-fp16') },
    @{ Name = 'splat-tiles StopThePop K=4'; Args = @('--renderer', 'splat-tiles', '--sort-window', '4') },
    @{ Name = 'splat-tiles StopThePop K=8'; Args = @('--renderer', 'splat-tiles', '--sort-window', '8') },
    @{ Name = 'splat-tiles StopThePop K=16'; Args = @('--renderer', 'splat-tiles', '--sort-window', '16') },
    @{ Name = 'splat-tiles StopThePop K=32'; Args = @('--renderer', 'splat-tiles', '--sort-window', '32') }
)
$lines = @()
$lines += '# Phase 6: compiled-pipeline statistics'
$lines += ''
$lines += 'Generated by `tools/run_pipeline_stats.ps1` (`gsplat --pipeline-stats`, VK_KHR_pipeline_executable_properties).'
$lines += 'Local memory = the driver''s "Local Memory Size" minus 2^36 (see the script header). Occupancy:'
$lines += 'resident threads per SM allowed by registers, threads and shared memory (Ada: 65536 regs, 1536 threads, 100 KB).'
$lines += ''
$lines += '| configuration | pipeline | registers / thread | shared memory / workgroup (B) | local memory / thread (B) | binary (B) | workgroup | occupancy (threads / SM) |'
$lines += '|---|---|---|---|---|---|---|---|'
foreach ($c in $configs) {
    $safe = ($c.Name -replace '[^A-Za-z0-9]+', '_').Trim('_')
    $json = Join-Path $OutDir "phase6_pipeline_stats_$safe.json"
    & $exe @(@('--scene', $Scene) + $c.Args + @('--pipeline-stats', $json)) *> "$json.log"
    if ($LASTEXITCODE -ne 0) { throw "gsplat --pipeline-stats failed for $($c.Name)" }
    Remove-Item "$json.log"
    $j = Get-Content $json -Raw | ConvertFrom-Json
    foreach ($p in $j.pipelines) {
        foreach ($e in $p.executables) {
            $s = $e.statistics
            $regs = [double]$s.'Register Count'
            $shared = [double]$s.'Shared Memory Size'
            $local = [double]$s.'Local Memory Size'
            if ($local -ge 68719476736) { $local -= 68719476736 }
            # Workgroup size: render passes 16x16 (8x8 for tile 8); every other compute pass 256 or 1.
            $wg = 256
            if ($p.pipeline -like 'tile_setup*' -or $p.pipeline -like '*radix setup*') { $wg = 1 }
            if ($p.pipeline -like 'tile_render*' -and $c.Name -like '*tile 8*') { $wg = 64 }
            $occ = '-'
            if ($e.name -eq 'CS' -or $e.name -like '*Compute*') {
                $warps = [math]::Ceiling($wg / 32)
                $regsPerWarp = [math]::Ceiling($regs * 32 / 256) * 256
                $byRegs = [math]::Floor(65536 / ($regsPerWarp * $warps))
                $byThreads = [math]::Floor(1536 / ($warps * 32))
                $byShared = if ($shared -gt 0) { [math]::Floor(102400 / $shared) } else { 99 }
                $wgs = [math]::Min([math]::Min($byRegs, $byThreads), [math]::Min($byShared, 24))
                $occ = "{0} ({1} WG)" -f ($wgs * $warps * 32), $wgs
            }
            $lines += ("| {0} | {1} [{2}] | {3} | {4} | {5} | {6} | {7} | {8} |" -f $c.Name, $p.pipeline, $e.name, [long]$regs, [long]$shared,
                [long]$local, [long]$s.'Binary Size', $wg, $occ)
        }
    }
}
$lines | Set-Content -Encoding utf8 $Markdown
$lines | ForEach-Object { Write-Host $_ }
